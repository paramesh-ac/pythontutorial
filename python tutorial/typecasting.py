# typecasting is the process of converting the value of  one data type to another data type 
# int(),float(),str(),bool() are the built in functions used for typecasting


x=10
y=20.5
name="paramesh"
is_student=True
print(x)
print(type(x))
print(y)
print(type(y))
print(name)
print(type(name))
print(is_student)
print(type(is_student))


# converting into the another data type 
print(int(y))
print(float(x))
print(str(is_student))
print(bool(name))

print(F"{type(y)} - {type(x)} - {type(is_student)} - {type(name)}")